CREATE DATABASE IF NOT EXISTS LANCHONETE;
USE LANCHONETE;

CREATE TABLE IF NOT EXISTS FORNECEDOR(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL,
    CONTATO VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS ESTOQUE(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL UNIQUE,
    QTD INT NOT NULL,
    UNIDADE_MEDIDA VARCHAR(255) NOT NULL,
    FORNECEDOR_ID INT NOT NULL,
    
    CONSTRAINT FK_FORNECEDOR_ESTOQUE 
		FOREIGN KEY(FORNECEDOR_ID)
		REFERENCES FORNECEDOR(ID)
);

CREATE TABLE IF NOT EXISTS PROMOCAO(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL,
    DT_INICIO DATE NOT NULL,
    DT_FINAL DATE NOT NULL,
    VALOR_PERCENTUAL DECIMAL(10,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS CATEGORIA(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS CARDAPIO(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL UNIQUE,
    PRECO_BASE DECIMAL(10,2) NOT NULL,
    CATEGORIA_ID INT NOT NULL,
    PROMOCAO_ID INT,
    
    CONSTRAINT FK_CATEGORIA_CARDAPIO
		FOREIGN KEY(CATEGORIA_ID)
        REFERENCES CATEGORIA(ID),
        
	CONSTRAINT FK_PROMOCAO_CARDAPIO
		FOREIGN KEY(PROMOCAO_ID)
        REFERENCES PROMOCAO(ID)
);

CREATE TABLE IF NOT EXISTS CARDAPIO_HAS_ESTOQUE(
    QTD INT NOT NULL,
    CARDAPIO_ID INT NOT NULL,
    ESTOQUE_ID INT NOT NULL,
    
    CONSTRAINT FK_CARDAPIO_CARDAPIO_HAS_ESTOQUE
		FOREIGN KEY(CARDAPIO_ID)
		REFERENCES CARDAPIO(ID),
    
    CONSTRAINT FK_ESTOQUE_CARDAPIO_HAS_ESTOQUE
		FOREIGN KEY(ESTOQUE_ID)
		REFERENCES ESTOQUE(ID)
);

CREATE TABLE IF NOT EXISTS AVALIACAO(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    NOTA DECIMAL(10,2) NOT NULL,
    COMENTARIO TEXT
);

CREATE TABLE IF NOT EXISTS MESA(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    QTD_CADEIRA INT NOT NULL,
    OCUPADA BOOLEAN NOT NULL DEFAULT FALSE,
    NUMERO INT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS CUPOM(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL,
    VALOR_PERCENTUAL DECIMAL(10,2) NOT NULL,
    VALIDADE DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS PAGAMENTO(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    DINHEIRO DECIMAL(10,2),
    PIX DECIMAL(10,2),
    CARTAO DECIMAL(10,2)
);

CREATE TABLE IF NOT EXISTS ENDERECO(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    RUA VARCHAR(255) NOT NULL,
    NUMERO INT NOT NULL,
    CEP VARCHAR(255) NOT NULL,
    BAIRRO VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS CLIENTE(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    CONTATO VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS CLIENTE_HAS_ENDERECO(
	ENDERECO_ID INT NOT NULL,
    CLIENTE_ID INT NOT NULL,

	CONSTRAINT FK_ENDERECO_CLIENTE_HAS_ENDERECO
		FOREIGN KEY(ENDERECO_ID)
        REFERENCES ENDERECO(ID),
        
	CONSTRAINT FK_CLIENTE_CLIENTE_HAS_ENDERECO
		FOREIGN KEY(CLIENTE_ID)
        REFERENCES CLIENTE(ID)
);

CREATE TABLE IF NOT EXISTS TRABALHADOR(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL,
    CONTATO VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS STATUS_CARGO(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    DT_INICIO DATETIME NOT NULL,
    DT_FINAL DATETIME,
    CARGO VARCHAR(255) NOT NULL,
    TRABALHADOR_ID INT NOT NULL,
    
    CONSTRAINT FK_TRABALHADOR_STATUS_CARGO
		FOREIGN KEY(TRABALHADOR_ID)
        REFERENCES TRABALHADOR(ID)
);

CREATE TABLE IF NOT EXISTS PEDIDO(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    TIPO_PEDIDO VARCHAR(255) NOT NULL,
    TIPO_ENTREGA VARCHAR(255) NOT NULL,
    VARIACAO_PEDIDO VARCHAR(255),
    ADICIONAL_PEDIDO VARCHAR(255),
    OBSERVACOES_PEDIDO VARCHAR(255),
    CLIENTE_ID INT,
    MESA_ID INT,
    CUPOM_ID INT,
    AVALIACAO_ID INT,
    PAGAMENTO_ID INT NOT NULL,
    
    CONSTRAINT FK_CLIENTE_PEDIDO
		FOREIGN KEY(CLIENTE_ID)
        REFERENCES CLIENTE(ID),
        
	CONSTRAINT FK_MESA_PEDIDO
		FOREIGN KEY(MESA_ID)
        REFERENCES MESA(ID),
        
	CONSTRAINT FK_CUPOM_PEDIDO
		FOREIGN KEY(CUPOM_ID)
        REFERENCES CUPOM(ID),
        
	CONSTRAINT FK_AVALIACAO_PEDIDO
		FOREIGN KEY(AVALIACAO_ID)
        REFERENCES AVALIACAO(ID),
        
	CONSTRAINT FK_PAGAMENTO_PEDIDO
		FOREIGN KEY(PAGAMENTO_ID)
        REFERENCES PAGAMENTO(ID)
);

CREATE TABLE IF NOT EXISTS IS_COMBO(
	CARDAPIO_ID INT NOT NULL,
    PEDIDO_ID INT NOT NULL,

	CONSTRAINT FK_CARDAPIO_IS_COMBO
		FOREIGN KEY(CARDAPIO_ID)
        REFERENCES CARDAPIO(ID),
        
	CONSTRAINT FK_PEDIDO_IS_COMBO
		FOREIGN KEY(PEDIDO_ID)
        REFERENCES PEDIDO(ID)
);

CREATE TABLE IF NOT EXISTS STATUS_PEDIDO(
	ID INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    STATUS_PEDIDO VARCHAR(255) NOT NULL,
    DT DATETIME NOT NULL,
    PEDIDO_ID INT NOT NULL,
    
    CONSTRAINT FK_PEDIDO_STATUS_PEDIDO
		FOREIGN KEY(PEDIDO_ID)
        REFERENCES PEDIDO(ID)
);

CREATE TABLE IF NOT EXISTS TRABALHADOR_HAS_PEDIDO(
	TRABALHADOR_ID INT NOT NULL,
    PEDIDO_ID INT NOT NULL,

	CONSTRAINT FK_TRABALHADOR_TRABALHADOR_HAS_PEDIDO
		FOREIGN KEY(TRABALHADOR_ID)
        REFERENCES TRABALHADOR(ID),
        
	CONSTRAINT FK_PEDIDO_TRABALHADOR_HAS_PEDIDO
		FOREIGN KEY(PEDIDO_ID)
        REFERENCES PEDIDO(ID)
);